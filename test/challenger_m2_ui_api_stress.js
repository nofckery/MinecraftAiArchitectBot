// Minimal DOM simulation for unit testing frontend chip sync
function createMockClassList(initial = []) {
  const set = new Set(initial);
  return {
    add: (...tokens) => tokens.forEach(t => set.add(t)),
    remove: (...tokens) => tokens.forEach(t => set.delete(t)),
    toggle: (token, force) => {
      if (force === true) set.add(token);
      else if (force === false) set.delete(token);
      else if (set.has(token)) set.delete(token);
      else set.add(token);
      return set.has(token);
    },
    contains: (token) => set.has(token),
    get size() { return set.size; }
  };
}

function createMockElement(tagName, id = '', initialAttrs = {}) {
  const listeners = {};
  const dataset = {};
  const classList = createMockClassList();

  const el = {
    tagName: tagName.toUpperCase(),
    id,
    dataset,
    classList,
    style: {},
    children: [],
    _innerHTML: '',
    value: '',
    checked: false,
    onclick: null,
    addEventListener(event, fn) {
      if (!listeners[event]) listeners[event] = [];
      listeners[event].push(fn);
    },
    removeEventListener(event, fn) {
      if (!listeners[event]) return;
      listeners[event] = listeners[event].filter(f => f !== fn);
    },
    dispatchEvent(event) {
      const type = event.type || event;
      if (listeners[type]) {
        listeners[type].forEach(fn => fn(event));
      }
      return true;
    },
    querySelectorAll(selector) {
      const results = [];
      function recurse(node) {
        for (const child of node.children) {
          if (selector.startsWith('.') && child.classList.contains(selector.slice(1))) {
            results.push(child);
          } else if (selector.startsWith('#') && child.id === selector.slice(1)) {
            results.push(child);
          } else if (child.tagName === selector.toUpperCase()) {
            results.push(child);
          }
          recurse(child);
        }
      }
      recurse(el);
      return results;
    },
    querySelector(selector) {
      return el.querySelectorAll(selector)[0] || null;
    },
    get innerHTML() {
      return el._innerHTML;
    },
    set innerHTML(html) {
      el._innerHTML = html;
      // Parse simple button markup generated by setupVersionChips
      el.children = [];
      const regex = /<button[^>]*class="([^"]*)"[^>]*data-ver="([^"]*)"[^>]*>([\s\S]*?)<\/button>/g;
      let match;
      while ((match = regex.exec(html)) !== null) {
        const btn = createMockElement('button');
        match[1].split(/\s+/).filter(Boolean).forEach(c => btn.classList.add(c));
        btn.dataset.ver = match[2];
        btn.textContent = match[3];
        el.children.push(btn);
      }
    }
  };

  for (const [k, v] of Object.entries(initialAttrs)) {
    if (k === 'class') {
      v.split(/\s+/).forEach(c => el.classList.add(c));
    } else if (k.startsWith('data-')) {
      el.dataset[k.replace('data-', '')] = v;
    } else {
      el[k] = v;
    }
  }

  return el;
}

class MockDocument {
  constructor() {
    this.elements = new Map();
  }
  register(el) {
    if (el.id) this.elements.set(el.id, el);
    return el;
  }
  getElementById(id) {
    return this.elements.get(id) || null;
  }
  querySelector(sel) {
    for (const el of this.elements.values()) {
      if (sel.startsWith('#') && el.id === sel.slice(1)) return el;
    }
    return null;
  }
  querySelectorAll(sel) {
    const list = [];
    for (const el of this.elements.values()) {
      if (sel.startsWith('.') && el.classList.contains(sel.slice(1))) list.push(el);
    }
    return list;
  }
}

